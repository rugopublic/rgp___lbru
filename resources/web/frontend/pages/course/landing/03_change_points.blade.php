{{--
1. Коэффициент удержания внимания (Attention Rate)
Что считаем: Отношение времени нахождения в блоке «Точки изменения» ко времени в блоке «Болевые точки».
UX-цель: Время должно быть сопоставимо. Если пользователь «завис» на болях, но пролетел «изменения» — значит, решение не выглядит адекватным ответом на проблему.
2. Паттерн «Сравнение» (Reciprocal Scrolling)
Что считаем: Скролл назад (вверх) к блоку «Болевые точки» и возврат к «Точкам изменения».
UX-цель: Это доказывает, что пользователь проводит в голове аналитическую сверку «Было/Стало». Высокий показатель этого микродвижения — признак глубокого вовлечения скептика.
3. Тепловая карта кликов по карточкам (Feature Engagement)
Что считаем: Клики или длительные наведения (Hover) на заголовки карточек (2-3 слова).
UX-цель: Выявить, какая именно «трансформация» является самым сильным драйвером. Это помогает в будущем менять порядок карточек, ставя самую кликабельную первой.
4. Метрика «Доверие к переходу» (Drop-off Rate)
Что считаем: Процент ухода с лендинга (Exit) сразу после этого блока.
UX-цель: В идеале — близок к нулю. Если пользователь уходит здесь, значит, «Точки изменения» прозвучали как нереалистичное обещание (инфоцыганство), и он потерял интерес.
5. Скорость перехода к действию (Action Velocity)
Что считаем: Время от момента входа в блок «Точки изменения» до клика по кнопке в следующем блоке («Обещания пользы»).
UX-цель: Чем быстрее клик, тем выше «энергия желания», созданная контрастом между болью и изменением.
